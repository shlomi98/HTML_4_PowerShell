// Dark Mode
const darkModeToggle = document.getElementById('darkModeToggle');
const moonIcon = document.getElementById('moonIcon');
const sunIcon = document.getElementById('sunIcon');

// Check for saved dark mode preference
if (localStorage.getItem('color-theme') === 'dark' || (!('color-theme' in localStorage) && window.matchMedia('(prefers-color-scheme: dark)').matches)) {
    document.documentElement.classList.add('dark');
    moonIcon.classList.add('hidden');
    sunIcon.classList.remove('hidden');
} else {
    document.documentElement.classList.remove('dark')
    moonIcon.classList.remove('hidden');
    sunIcon.classList.add('hidden');
}

darkModeToggle.addEventListener('click', () => {
    // toggle icons
    moonIcon.classList.toggle('hidden');
    sunIcon.classList.toggle('hidden');

    // if set via local storage previously
    if (localStorage.getItem('color-theme')) {
        if (localStorage.getItem('color-theme') === 'light') {
            document.documentElement.classList.add('dark');
            localStorage.setItem('color-theme', 'dark');
        } else {
            document.documentElement.classList.remove('dark');
            localStorage.setItem('color-theme', 'light');
        }
    // if NOT set via local storage previously
    } else {
        if (document.documentElement.classList.contains('dark')) {
            document.documentElement.classList.remove('dark');
            localStorage.setItem('color-theme', 'light');
        } else {
            document.documentElement.classList.add('dark');
            localStorage.setItem('color-theme', 'dark');
        }
    }
});


const btnGenerate = document.getElementById('generate');
const btnCopy = document.getElementById('copy');
const copyMsg = document.getElementById('copyMsg');
const outputSection = document.getElementById('outputSection');

// Form elements
const delegateUpnInput = document.getElementById('delegateUpn');
const ownersInput = document.getElementById('owners');
const accessRightSelect = document.getElementById('accessRight');
const actionToggle = document.getElementById('actionToggle');
const formSectionTitle = document.getElementById('formSectionTitle');

// Error message elements
const delegateUpnError = document.getElementById('delegateUpnError');
const ownersError = document.getElementById('ownersError');

const validateAndToggleButton = () => {
    const delegateValid = delegateUpnInput.value.trim() !== '';
    const ownersValid = ownersInput.value.trim() !== '';
    btnGenerate.disabled = !(delegateValid && ownersValid);
};

const updateFormForAction = () => {
    const isAddAction = actionToggle.checked;
    if (isAddAction) {
        formSectionTitle.textContent = '1️⃣ הגדרת הרשאות להוספה';
        accessRightSelect.parentElement.style.display = 'block';
    } else {
        formSectionTitle.textContent = '1️⃣ הגדרת הרשאות להסרה';
        accessRightSelect.parentElement.style.display = 'none';
    }
};

// Initial setup
document.addEventListener('DOMContentLoaded', () => {
    validateAndToggleButton();
    updateFormForAction();
});


// Add event listeners
delegateUpnInput.addEventListener('input', validateAndToggleButton);
ownersInput.addEventListener('input', validateAndToggleButton);
actionToggle.addEventListener('change', updateFormForAction);


btnGenerate.addEventListener('click', () => {
    let isValid = true;

    // Hide previous errors
    delegateUpnError.classList.add('hidden');
    ownersError.classList.add('hidden');

    const delegate = delegateUpnInput.value.trim();
    const ownersRaw = ownersInput.value.trim();
    const right = accessRightSelect.value;
    const includeErr = document.getElementById('errAction').checked;
    const isAddAction = actionToggle.checked;

    if (!delegate) {
        delegateUpnError.classList.remove('hidden');
        isValid = false;
    }

    if (!ownersRaw) {
        ownersError.classList.remove('hidden');
        isValid = false;
    }

    if (!isValid) {
        return;
    }

    // Parse owners by commas/newlines/semicolons
    const owners = ownersRaw.split(/[\n,;]+/).map(o => o.trim()).filter(Boolean);
    if (!owners.length) {
        ownersError.textContent = 'חייב להיות לפחות Owner אחד.';
        ownersError.classList.remove('hidden');
        return;
    } else {
        ownersError.textContent = 'שדה זה חובה.'; // Reset message
    }

    outputSection.classList.remove('hidden');

    const errFlag = includeErr ? '-ErrorAction SilentlyContinue' : '';

    let script = `# ===== Generated by Permission Helper =====\n`;
    script    += `# Action: ${isAddAction ? 'Add' : 'Remove'} Permissions\n`;
    script    += `Connect-ExchangeOnline\n\n`;
    script    += `$delegate = \"${delegate}\"\n`;
    script    += `$owners   = @(${owners.map(o => `\"${o}\"`).join(', ')})\n`;
    if (isAddAction) {
      script  += `$right    = \"${right}\"\n`;
    }
    script    += `\n`;
    script    += `foreach ($o in $owners) {\n`;
    script    += `    $cal = (Get-MailboxFolderStatistics $o | Where-Object { $_.FolderType -eq 'Calendar' } | Select-Object -First 1 -ExpandProperty FolderPath)\n`;
    script    += `    if (-not $cal) {\n`;
    script    += `        # נסיון חוזר בעברית\n`;
    script    += `        $cal = (Get-MailboxFolderStatistics $o | Where-Object { $_.Name -eq 'יומן' } | Select-Object -First 1 -ExpandProperty FolderPath)\n`;
    script    += `    }\n`;
    script    += `    if (-not $cal) { Write-Warning \"$o – תיקיית יומן לא נמצאה\"; continue }\n`;
    script    += `    $id = \"$o\`:$cal\"\n`;
    script    += `    Try {\n`;
    if (isAddAction) {
        script += `        Add-MailboxFolderPermission -Identity $id -User $delegate -AccessRights $right ${errFlag}\n`;
        script += `        Write-Host \"✓ Added $delegate to $id with '$right' rights\"\n`;
    } else {
        script += `        Remove-MailboxFolderPermission -Identity $id -User $delegate -Confirm:$false ${errFlag}\n`;
        script += `        Write-Host \"✓ Removed $delegate from $id\"\n`;
    }
    script    += `    } Catch {\n`;
    script    += `        Write-Warning \"❌ Failed to process $id. Error: $($_.Exception.Message)\"\n`;
    script    += `    }\n`;
    script    += `}\n\n`;
    script    += `Write-Host \"--- Verifying permissions for $delegate ---\"\n`;
  script    += `foreach ($o in $owners) {\n`;
  script    += `    $cal = (Get-MailboxFolderStatistics $o | Where-Object { $_.FolderType -eq 'Calendar' } | Select-Object -First 1 -ExpandProperty FolderPath)\n`;
  script    += `    if (-not $cal) {\n`;
  script    += `        $cal = (Get-MailboxFolderStatistics $o | Where-Object { $_.Name -eq 'יומן' } | Select-Object -First 1 -ExpandProperty FolderPath)\n`;
  script    += `    }\n`;
  script    += `    if ($cal) { Get-MailboxFolderPermission \"$o\`:$cal\" | Where-Object { $_.User -eq $delegate } | Format-Table FolderName,User,AccessRights }\n`;
  script    += `}\n`;
  script    += `# =========================================`;

  document.getElementById('output').value = script;
});

btnCopy.addEventListener('click', async () => {
  const text = document.getElementById('output').value;
  if (!text) return;
  try {
    await navigator.clipboard.writeText(text);
    copyMsg.textContent = '✅ הועתק!';
    setTimeout(()=> copyMsg.textContent='', 3000);
  } catch (err) {
    copyMsg.textContent = '❌ לא הצליח להעתיק';
  }
});
